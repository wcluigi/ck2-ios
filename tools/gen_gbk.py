"""Generate runtime/mobile/gbk_table.c: code page 936 (GBK) <-> UTF-16 tables + converters."""
import os
here = os.path.dirname(os.path.abspath(__file__))
fwd = []
for lead in range(0x81, 0xFF):
    for trail in range(0x40, 0xFF):
        try:
            u = bytes([lead, trail]).decode('cp936')
            fwd.append(ord(u) if len(u) == 1 and ord(u) < 0x10000 else 0)
        except UnicodeDecodeError:
            fwd.append(0)
pairs = sorted({(u, ((i // 191 + 0x81) << 8) | (i % 191 + 0x40)) for i, u in enumerate(fwd) if u})
out = ['// generated by tools/gen_gbk.py', '#include "rt.h"',
       'static const u16 gbk2u[%d] = {' % len(fwd)]
for k in range(0, len(fwd), 24):
    out.append(','.join(str(v) for v in fwd[k:k + 24]) + ',')
out.append('};')
out.append('static const u16 u2gbk_u[%d] = {' % len(pairs))
for k in range(0, len(pairs), 24):
    out.append(','.join(str(p[0]) for p in pairs[k:k + 24]) + ',')
out.append('};')
out.append('static const u16 u2gbk_g[%d] = {' % len(pairs))
for k in range(0, len(pairs), 24):
    out.append(','.join(str(p[1]) for p in pairs[k:k + 24]) + ',')
out.append('};')
out.append(r'''
int gbk_to_utf16(const u8 *s, int n, u16 *out, int outmax) {   // n < 0: up to NUL (not included)
    int o = 0;
    for (int i = 0; n < 0 ? s[i] != 0 : i < n; i++) {
        u32 b = s[i], u = b;
        if (b == 0x80) u = 0x20ac;
        else if (b > 0x80 && b < 0xff && (n < 0 ? s[i + 1] != 0 : i + 1 < n) && s[i + 1] >= 0x40 && s[i + 1] < 0xff) {
            u = gbk2u[(b - 0x81) * 191 + (s[i + 1] - 0x40)];
            if (!u) u = '?';
            i++;
        } else if (b > 0x80) u = '?';
        if (out && o < outmax) out[o] = (u16)u;
        o++;
    }
    return o;
}
int utf16_to_gbk(const u16 *s, int n, u8 *out, int outmax) {
    int o = 0;
    for (int i = 0; n < 0 ? s[i] != 0 : i < n; i++) {
        u32 u = s[i];
        if (u < 0x80) { if (out && o < outmax) out[o] = (u8)u; o++; continue; }
        if (u == 0x20ac) { if (out && o < outmax) out[o] = 0x80; o++; continue; }
        int lo = 0, hi = (int)(sizeof u2gbk_u / 2) - 1, g = -1;
        while (lo <= hi) { int m = (lo + hi) / 2; if (u2gbk_u[m] == u) { g = u2gbk_g[m]; break; } if (u2gbk_u[m] < u) lo = m + 1; else hi = m - 1; }
        if (g < 0) { if (out && o < outmax) out[o] = '?'; o++; continue; }
        if (out && o + 1 < outmax) { out[o] = (u8)(g >> 8); out[o + 1] = (u8)g; }
        o += 2;
    }
    return o;
}
''')
open(os.path.join(here, '..', 'runtime', 'mobile', 'gbk_table.c'), 'w').write('\n'.join(out))
print(len(fwd), 'cells,', len(pairs), 'mapped')
